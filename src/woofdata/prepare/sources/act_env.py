"""Barkopedia Act_Env converter: bark clips labelled with the dog's activity and environment.

Raw files in raw/act_env/ (pinned Hugging Face commit):
    train/split1.zip, train/split2.zip   "split1/audio_00000.wav" ... (12,480 clips together)
    train/train_label.csv                columns audio_id, environement (sic), activity
    validation/valid_audios.zip          "validation/audio_00000.wav" ... (500 clips)
    validation/valid_labels.csv          same columns
Validation ids reuse the train ids (audio_00000 ...), so clip ids include the author split.
Labels come from a vision-language model, so every row is train_only and never evaluated;
labels.csv keeps the author split for early stopping. One row per whole clip, no windows.
"""

from __future__ import annotations

import statistics
from collections import Counter
from pathlib import Path, PurePosixPath

import soundfile

from woofdata.download.datasets import dataset_config
from woofdata.prepare.manifest import ManifestRow, make_clip_id
from woofdata.prepare.utils.archives import list_archive_members, open_archive, open_member
from woofdata.prepare.utils.audio import convert_audio
from woofdata.prepare.utils.label_files import write_labels
from woofdata.utils_fileio import read_csv, relative_data_path
from woofdecoder.taxonomy import OTHER_CATEGORY

SOURCE: str = "act_env"
# Author split -> label CSV and audio zips, relative to raw/act_env/.
LABEL_FILES: dict[str, str] = {
    "train": "train/train_label.csv",
    "validation": "validation/valid_labels.csv",
}
AUDIO_ZIPS: dict[str, list[str]] = {
    "train": ["train/split1.zip", "train/split2.zip"],
    "validation": ["validation/valid_audios.zip"],
}
MACOS_FOLDER: str = "__MACOSX/"
AUDIO_SUFFIX: str = ".wav"
AUDIO_DIRNAME: str = "audio"
ACTIVITY_COLUMN: str = "activity"
ENVIRONMENT_COLUMN: str = "environement"  # spelled this way in the authors' CSVs

# Activity -> taxonomy category; activities outside the 4 situations map to OTHER_CATEGORY.
ACTIVITY_TO_CATEGORY: dict[str, str] = {
    "alerting to sounds": "alert_aggressive",
    "begging for food": "attention_seeking",
    "seeking attention": "attention_seeking",
    "playing with human": "playful_excited",
    "playing with other animals": "playful_excited",
    "playing with toy": "playful_excited",
    "rest": OTHER_CATEGORY,
    "taking shower": OTHER_CATEGORY,
}

LEAKAGE_GROUP: str = "barkopedia_pool"
SOURCE_LICENSE: str = "MIT"
NOTES: str = (
    "labels generated by a vision-language model from the video, then manually checked; "
    "MIT tag in YAML only; audio is online-video content, do not redistribute"
)
# The environment, lowercased and trimmed, so "Indoor (General)" and "indoor (general)"
# count as one value. The raw column stays next to it.
NORMALIZED_ENVIRONMENT_COLUMN: str = "environment_normalized"
LABEL_COLUMNS: list[str] = [
    "clip_id",
    "audio_id",
    ENVIRONMENT_COLUMN,
    NORMALIZED_ENVIRONMENT_COLUMN,
    ACTIVITY_COLUMN,
    "original_split",
]
RARE_VALUE_COUNT: int = 5  # environment values seen fewer times are listed in the report


def normalize_label(value: str) -> str:
    """Return value lowercased with surrounding spaces removed ("Rest " -> "rest")."""
    return value.strip().lower()


def check_activities(clips: list[dict[str, str]]) -> None:
    """Raise ValueError naming every activity value (with its count) not in the mapping.

    Matching ignores case and surrounding spaces; the authors' CSVs mix "Rest" and "rest".
    """
    unknown: Counter[str] = Counter()
    for clip in clips:
        if normalize_label(clip[ACTIVITY_COLUMN]) not in ACTIVITY_TO_CATEGORY:
            unknown[clip[ACTIVITY_COLUMN]] += 1
    if unknown:
        unknown_values = dict(sorted(unknown.items()))
        raise ValueError(f"activity values not in ACTIVITY_TO_CATEGORY: {unknown_values}")


def read_labels(raw_dir: Path) -> dict[str, dict[str, str]]:
    """Return {clip_id: label row} for both author splits, with the normalized environment
    and original_split added."""
    clips: dict[str, dict[str, str]] = {}
    for author_split, label_file in LABEL_FILES.items():
        for record in read_csv(raw_dir / label_file).to_dict("records"):
            clip_id = make_clip_id(SOURCE, f"{author_split}/{record['audio_id']}{AUDIO_SUFFIX}")
            added = {
                NORMALIZED_ENVIRONMENT_COLUMN: normalize_label(record[ENVIRONMENT_COLUMN]),
                "original_split": author_split,
            }
            clips[clip_id] = {"clip_id": clip_id} | record | added
    return clips


def wav_path_for(out_dir: Path, author_split: str, audio_id: str) -> Path:
    """Return processed/act_env/audio/<author split>/<audio_id>.wav."""
    return out_dir / AUDIO_DIRNAME / author_split / f"{audio_id}{AUDIO_SUFFIX}"


def make_row(
    clip: dict[str, str], out_dir: Path, duration_s: float, source_version: str
) -> ManifestRow:
    """Return the manifest row of one converted clip."""
    wav_path = wav_path_for(out_dir, clip["original_split"], clip["audio_id"])
    return ManifestRow(
        clip_id=clip["clip_id"],
        source=SOURCE,
        source_version=source_version,
        source_license=SOURCE_LICENSE,
        leakage_group=LEAKAGE_GROUP,
        split="train_only",
        modality="audio",
        file_path=relative_data_path(wav_path),
        start_s=0.0,
        end_s=round(duration_s, 6),
        original_label=clip[ACTIVITY_COLUMN],
        label_type="context",
        label_provenance="vlm_video",
        mapped_category=ACTIVITY_TO_CATEGORY[normalize_label(clip[ACTIVITY_COLUMN])],
        eval_allowed=False,
        notes=NOTES,
    )


def convert_zip(
    zip_path: Path, author_split: str, clips: dict[str, dict[str, str]], out_dir: Path
) -> tuple[dict[str, float], list[str], list[str]]:
    """Convert every labelled WAV in one zip (opened once).

    Returns:
        ({clip_id: duration in seconds}, clip ids that failed to decode, audio ids in the
        zip without a label row). Failed and unlabelled clips get no manifest row.
    """
    durations: dict[str, float] = {}
    failed: list[str] = []
    unlabelled: list[str] = []
    with open_archive(zip_path) as archive:
        for member_name in sorted(list_archive_members(zip_path)):
            if member_name.startswith(MACOS_FOLDER) or not member_name.endswith(AUDIO_SUFFIX):
                continue
            audio_id = PurePosixPath(member_name).stem
            clip_id = make_clip_id(SOURCE, f"{author_split}/{audio_id}{AUDIO_SUFFIX}")
            if clip_id not in clips:
                unlabelled.append(audio_id)
                continue
            wav_path = wav_path_for(out_dir, author_split, audio_id)
            with open_member(archive, member_name) as audio_file:
                audio_bytes = audio_file.read()
            try:
                durations[clip_id] = convert_audio(audio_bytes, wav_path)
            except soundfile.LibsndfileError:
                failed.append(clip_id)
    return durations, failed, unlabelled


def print_counts(title: str, values: list[str]) -> None:
    """Print one "title: {value: count}" line, most common first."""
    print(f"  {title}: {dict(Counter(values).most_common())}")


def print_report(
    rows: list[ManifestRow], clips: dict[str, dict[str, str]], durations: list[float]
) -> None:
    """Print clips per (normalized) activity, environment and mapped category, the rare
    environment values, and the duration range."""
    activities: list[str] = []
    environments: list[str] = []
    categories: list[str] = []
    for row in rows:
        activities.append(normalize_label(row.original_label))
        environments.append(clips[row.clip_id][NORMALIZED_ENVIRONMENT_COLUMN])
        categories.append(row.mapped_category)
    print_counts("clips per activity (normalized)", activities)
    print_counts("clips per environment (normalized)", environments)
    print_counts("clips per mapped category", categories)
    rare_values: list[str] = []
    for environment, count in sorted(Counter(environments).items()):
        if count < RARE_VALUE_COUNT:
            rare_values.append(f"{environment!r} ({count})")
    print(f"  environments seen fewer than {RARE_VALUE_COUNT} times: {', '.join(rare_values)}")
    median_s = statistics.median(durations)
    print(
        f"  duration s: min {min(durations):.2f}, median {median_s:.2f}, max {max(durations):.2f}"
    )


def prepare(raw_dir: Path, out_dir: Path) -> list[ManifestRow]:
    """Convert both author splits into WAVs, labels.csv and train_only rows.

    Raises:
        ValueError: If an activity is not in ACTIVITY_TO_CATEGORY (checked before any audio
            is converted), or a labelled clip is in none of the zips.
    """
    clips = read_labels(raw_dir)
    check_activities(list(clips.values()))
    source_version = dataset_config(SOURCE)["revision"]

    durations: dict[str, float] = {}
    failed: list[str] = []
    for author_split, zip_names in AUDIO_ZIPS.items():
        for zip_name in zip_names:
            zip_durations, zip_failed, unlabelled = convert_zip(
                raw_dir / zip_name, author_split, clips, out_dir
            )
            durations.update(zip_durations)
            failed.extend(zip_failed)
            if unlabelled:
                print(f"  {zip_name}: {len(unlabelled)} clips without labels, skipped")

    rows: list[ManifestRow] = []
    label_rows: list[dict[str, str]] = []
    for clip_id, clip in sorted(clips.items()):
        if clip_id in durations:
            rows.append(make_row(clip, out_dir, durations[clip_id], source_version))
            label_rows.append(clip)
        elif clip_id not in failed:
            raise ValueError(f"{clip_id} has a label row but is in no audio zip")

    write_labels(out_dir, label_rows, LABEL_COLUMNS)
    print_report(rows, clips, list(durations.values()))
    print(f"  failed to decode: {len(failed)} {sorted(failed)}")
    return rows
